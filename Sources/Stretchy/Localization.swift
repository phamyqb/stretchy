func currentLanguage() -> String {
    let pref = AppSettings.shared.language
    if pref == "en" || pref == "vi" { return pref }
    let first = Locale.preferredLanguages.first ?? "en"
    return first.hasPrefix("vi") ? "vi" : "en"
}

/// Dịch một key theo ngôn ngữ đang chọn. Hỗ trợ format (%d, %@).
func tr(_ key: String, _ args: CVarArg...) -> String {
    guard let entry = L10n.table[key] else { return key }
    let format = currentLanguage() == "vi" ? entry.vi : entry.en
    return args.isEmpty ? format : String(format: format, arguments: args)
}
